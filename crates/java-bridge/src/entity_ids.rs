/// Java entity-type id for a Bedrock network type id on `protocol`.
///
/// `None` for a legacy client (no per-version table), for an unknown Bedrock
/// type, or for a type that has no Java counterpart.
pub fn entity_type_id(protocol: i32, bedrock_id: &str) -> Option<i32> {
    let java = BEDROCK_TO_JAVA
        .iter()
        .find(|(bedrock, _)| *bedrock == bedrock_id)
        .map(|(_, java)| *java)?;
    table(protocol)?
        .iter()
        .find(|(name, _)| *name == java)
        .map(|(_, id)| *id)
}

fn table(protocol: i32) -> Option<&'static [(&'static str, i32)]> {
    match protocol {
        769 => Some(IDS_769),
        770 => Some(IDS_770),
        773 => Some(IDS_773),
        774 => Some(IDS_774),
        775 => Some(IDS_775),
        _ => None,
    }
}

