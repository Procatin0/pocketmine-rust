#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_cover_every_modern_protocol_in_registry_order() {
        for protocol in [769, 770, 773, 774, 775] {
            let table = table(protocol).expect("a table per modern protocol");
            assert!(
                table.len() > 60,
                "protocol {protocol} covers the spawnable types"
            );
            // Registry ids follow the (alphabetical) registry order, so the
            // names in each generated table must be strictly increasing.
            assert!(table.windows(2).all(|pair| pair[0].0 < pair[1].0));
        }
        assert_eq!(table(340), None);
    }

    #[test]
    fn falling_block_and_animals_resolve_per_version() {
        for protocol in [769, 770, 773, 774, 775] {
            assert!(entity_type_id(protocol, "minecraft:falling_block").is_some());
            assert!(entity_type_id(protocol, "minecraft:cow").is_some());
            assert!(entity_type_id(protocol, "minecraft:chicken").is_some());
        }
        assert_eq!(entity_type_id(769, "minecraft:falling_block"), Some(49));
        assert_eq!(entity_type_id(775, "minecraft:falling_block"), Some(51));
        assert_eq!(entity_type_id(775, "minecraft:cow"), Some(30));
    }

    #[test]
    fn types_without_a_java_counterpart_are_skipped() {
        assert_eq!(entity_type_id(775, "minecraft:ice_bomb"), None);
        assert_eq!(entity_type_id(340, "minecraft:cow"), None);
        assert_eq!(entity_type_id(775, "minecraft:nope"), None);
    }
}
