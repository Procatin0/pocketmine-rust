/// Default location used by the worker: `<temp>/pocketmine-rust-php`.
pub fn default_runtime_dir() -> PathBuf {
    std::env::temp_dir().join("pocketmine-rust-php")
}

/// Write every embedded PHP file into `dir` and return the path to
/// `bootstrap.php`.
///
/// On Windows an existing runtime may still be mapped by another process (for
/// example a previous server instance), in which case rewriting the files
/// fails with a sharing violation. When that happens we transparently retry in
/// a per-process directory (`<dir>-<pid>`) so a fresh worker can still start.
pub fn write_runtime(dir: &Path) -> io::Result<PathBuf> {
    match write_runtime_at(dir) {
        Ok(path) => Ok(path),
        Err(first_error) => {
            let fallback = fallback_runtime_dir(dir);
            match write_runtime_at(&fallback) {
                Ok(path) => {
                    tracing::warn!(
                        "Could not refresh PHP runtime in {} ({}); using {} instead",
                        dir.display(),
                        first_error,
                        fallback.display()
                    );
                    Ok(path)
                }
                Err(second_error) => Err(io::Error::new(
                    second_error.kind(),
                    format!(
                        "failed to write PHP runtime to {} ({}); fallback {} also failed ({})",
                        dir.display(),
                        first_error,
                        fallback.display(),
                        second_error
                    ),
                )),
            }
        }
    }
}

fn write_runtime_at(dir: &Path) -> io::Result<PathBuf> {
    fs::create_dir_all(dir)?;

    for (name, contents) in PHP_RUNTIME_FILES {
        fs::write(dir.join(name), contents.as_bytes())?;
    }

    Ok(dir.join("bootstrap.php"))
}

fn fallback_runtime_dir(dir: &Path) -> PathBuf {
    let name = dir
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("pocketmine-rust-php");
    dir.with_file_name(format!("{}-{}", name, std::process::id()))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::{SystemTime, UNIX_EPOCH};

    #[test]
    fn writes_all_runtime_files() {
        let unique = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let dir = std::env::temp_dir().join(format!(
            "pmrust-bootstrap-test-{}-{}",
            std::process::id(),
            unique
        ));

        let bootstrap = write_runtime(&dir).expect("runtime written");
        assert_eq!(bootstrap, dir.join("bootstrap.php"));
        assert!(bootstrap.exists());
        for (name, _) in PHP_RUNTIME_FILES {
            assert!(dir.join(name).exists(), "missing {}", name);
        }

        let _ = fs::remove_dir_all(&dir);
    }

    /// Regression test for the `Missing runtime file: .../bossbar.php` boot
    /// failure: `bootstrap.php` required `bossbar.php` but Rust never wrote
    /// it (the scoreboard agent added scoreboard to both lists and bossbar
    /// only to `bootstrap.php`), so the PHP worker exited before `ping`.
    ///
    /// The manifest in `php/runtime_files.php` must stay exactly in sync (same
    /// names, same order) with `PHP_RUNTIME_FILES` minus the two files nothing
    /// requires: `runtime_files.php` itself and `bootstrap.php`.
    #[test]
    fn runtime_list_matches_runtime_manifest() {
        assert_eq!(PHP_RUNTIME_FILES.len(), 61, "runtime file count");
        let manifest = PHP_RUNTIME_FILES
            .iter()
            .find(|(name, _)| *name == "runtime_files.php")
            .expect("runtime_files.php embedded")
            .1;
        let listed: Vec<&str> = manifest
            .lines()
            .filter_map(|line| {
                let line = line.trim();
                line.strip_prefix('\'')
                    .and_then(|rest| rest.strip_suffix("',"))
            })
            .collect();
        let embedded: Vec<&str> = PHP_RUNTIME_FILES
            .iter()
            .map(|(name, _)| *name)
            .filter(|name| *name != "bootstrap.php" && *name != "runtime_files.php")
            .collect();
        assert_eq!(
            listed, embedded,
            "runtime_files.php drifted from PHP_RUNTIME_FILES"
        );
        for name in ["bossbar.php", "scoreboard.php", "PlayerDataSaveEvent.php", "thread.php"] {
            assert!(embedded.contains(&name), "missing {}", name);
        }
    }
}
